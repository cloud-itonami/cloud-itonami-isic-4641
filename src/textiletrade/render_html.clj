(ns textiletrade.render-html
  "Build-time HTML renderer for `docs/samples/operator-console.html`.

  Closes flagship checklist item 2 for this repo (com-junkawasaki/root
  ADR-2607189300, Wave 6): `docs/samples/operator-console.html` existed
  here as a HAND-WRITTEN stub (raw hex colors, numbers typed by a human,
  no generator at all). This namespace replaces it with a page that is
  GENERATED by driving the REAL actor stack --
  `textiletrade.operation` (a langgraph StateGraph) -> `textiletrade.governor`
  (the independent Textile Trading Governor) -> `textiletrade.store`
  (the SSoT + append-only audit ledger) -- and rendering only what that
  run actually produced.

  Nothing on the page is a literal a human typed:

    - every textile-order row is read back out of the real seeded store
      AFTER the scenario has mutated it (`:dispatched?`/`:invoiced?`/
      `:dispatch-number`/`:invoice-number` are the real post-commit
      values written by `textiletrade.registry`);
    - every audit-ledger row is a real fact appended by the actor's own
      `:commit`/`:hold` nodes;
    - every HARD-hold rule and Japanese `:detail` string is the
      governor's own output, not a paraphrase;
    - the action-gate table is derived from this repo's own
      `textiletrade.phase/phases` + `textiletrade.governor/high-stakes`
      data structures rather than described by hand, so it cannot drift
      away from the code;
    - the jurisdiction table is derived from `textiletrade.facts`.

  DETERMINISM: the store carries no clock, the ledger is an ordered
  vector, `all-textile-orders` sorts by `:id`, the registry numbers are
  jurisdiction-scoped sequences, and no timestamp is rendered into the
  page. Two consecutive runs are byte-identical (verified by `cmp`).

  Usage: `clojure -M:dev:render-html [out-file]`
  (default `docs/samples/operator-console.html`)."
  (:require [clojure.string :as str]
            [jp-go-dds.skin :as skin]
            [langgraph.graph :as g]
            [textiletrade.facts :as facts]
            [textiletrade.governor :as governor]
            [textiletrade.operation :as op]
            [textiletrade.phase :as phase]
            [textiletrade.store :as store]))

(def ^:private operator
  "The same operator context this repo's own `textiletrade.sim` driver
  uses -- a phase-3 trading supervisor."
  {:actor-id "op-1" :actor-role :trading-supervisor :phase 3})

;; ----------------------------- the real run -----------------------------

(defn- exec! [actor tid request]
  (g/run* actor {:request request :context operator} {:thread-id tid}))

(defn- approve! [actor tid]
  (g/run* actor {:approval {:status :approved :by "op-1"}}
          {:thread-id tid :resume? true}))

(defn- step!
  "Runs ONE real operation through the compiled actor graph and, when the
  graph interrupts for a human (`:escalate`), resumes it with a real
  approval. Records the disposition the graph ACTUALLY reached on each
  pass, so the console's route column is observed rather than asserted.
  Returns the recorded route map."
  [actor runs tid request]
  (let [r1 (exec! actor tid request)
        d1 (get-in r1 [:state :disposition])
        r2 (when (= :escalate d1) (approve! actor tid))
        d2 (some-> r2 (get-in [:state :disposition]))
        run {:thread-id tid
             :op (:op request)
             :subject (:subject request)
             :first-pass d1
             :final (or d2 d1)
             :confidence (get-in (or r2 r1) [:state :verdict :confidence])}]
    (swap! runs conj run)
    run))

