;; ----------------------------- rendering helpers -----------------------------

(defn- esc [v]
  (-> (str v)
      (str/replace "&" "&amp;")
      (str/replace "<" "&lt;")
      (str/replace ">" "&gt;")
      (str/replace "\"" "&quot;")))

(defn- label [v] (if (keyword? v) (name v) (str v)))

(defn- clip
  "Deterministic display clip -- long legal-basis citations are real
  actor output but would otherwise dominate the table."
  [n s]
  (let [s (str s)]
    (if (> (count s) n) (str (subs s 0 n) "…") s)))

(defn- yes-no [b] (if b "yes" "no"))

(defn- route-badge [{:keys [first-pass final]}]
  (cond
    (= :hold first-pass) "<span class=\"critical\">HARD hold · never offered to a human</span>"
    (and (= :escalate first-pass) (= :commit final)) "<span class=\"warn\">human approved → committed</span>"
    (= :commit first-pass) "<span class=\"ok\">auto-committed (governor-clean)</span>"
    :else (str "<span class=\"muted\">" (esc (label final)) "</span>")))

;; ----------------------------- sections -----------------------------

(defn- order-row [ledger {:keys [id order-id goods-kind origin-region counterparty
                                 jurisdiction dispatched? invoiced?
                                 dispatch-number invoice-number] :as to}]
  (let [last-fact (last (filter #(= (:subject %) id) ledger))
        status (cond
                 (nil? last-fact) "<span class=\"muted\">no activity</span>"
                 (= :governor-hold (:t last-fact))
                 (str "<span class=\"critical\">HARD hold · "
                      (esc (label (-> last-fact :basis first))) "</span>")
                 :else "<span class=\"ok\">committed</span>")
        flagged? (facts/flagged-origin? origin-region)
        triggered? (facts/forced-labor-presumption-triggered? to)]
    (format (str "        <tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td>"
                 "<td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>")
            (esc id) (esc order-id) (esc goods-kind)
            (str (esc origin-region)
                 (when flagged?
                   (str " <span class=\"" (if triggered? "critical" "muted") "\">flagged origin"
                        (if triggered? " · presumption applies" " · jurisdiction not binding")
                        "</span>")))
            (esc counterparty) (esc jurisdiction)
            (if dispatched?
              (str "<span class=\"ok\">dispatched</span> <code>" (esc dispatch-number) "</code>")
              "<span class=\"muted\">not dispatched</span>")
            (if invoiced?
              (str "<span class=\"ok\">invoiced</span> <code>" (esc invoice-number) "</code>")
              "<span class=\"muted\">not invoiced</span>")
            status)))

(defn- evidence-row [{:keys [id jurisdiction credit-cleared? contract-terms
                             sanctions-screened?
                             supply-chain-traceability-documented?
                             forced-labor-rebuttal-evidence-on-file?]}]
  (format (str "        <tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td>"
               "<td>%s</td><td>%s</td><td>%s</td></tr>")
          (esc id) (esc jurisdiction)
          (yes-no credit-cleared?)
          (if (str/blank? (str contract-terms))
            "<span class=\"critical\">none on file</span>"
            (esc contract-terms))
          (yes-no sanctions-screened?)
          (yes-no supply-chain-traceability-documented?)
          (yes-no forced-labor-rebuttal-evidence-on-file?)))

(defn- gate-rows
  "Derived from this repo's OWN `textiletrade.phase/phases` +
  `textiletrade.governor/high-stakes`, so the table cannot drift away
  from the code it describes."
  []
  (let [ph phase/default-phase
        {:keys [label writes auto]} (get phase/phases ph)]
    (for [o (sort-by str phase/write-ops)]
      (format "        <tr><td><code>%s</code></td><td>%s</td></tr>"
              (esc o)
              (cond
                (contains? governor/high-stakes o)
                "<span class=\"warn\">ALWAYS human approval · never in any phase's <code>:auto</code> set</span>"
                (contains? auto o)
                (str "<span class=\"ok\">phase " ph " (" (esc label)
                     "): auto-commit when governor-clean</span>")
                (contains? writes o)
                (str "<span class=\"warn\">phase " ph ": human approval (not auto-eligible)</span>")
                :else
                (str "<span class=\"critical\">phase " ph ": disabled → hold</span>"))))))

(defn- hold-rows
  "One row per HARD rule the governor ACTUALLY fired in this run, with
  the governor's own `:detail` text."
  [ledger]
  (let [holds (filter #(= :governor-hold (:t %)) ledger)
        by-rule (->> holds
                     (mapcat (fn [h] (map (fn [v] [(:rule v) (:subject h) (:detail v) (:op h)])
                                          (:violations h))))
                     (group-by first))]
    (for [rule (sort-by str (keys by-rule))
          :let [entries (get by-rule rule)]]
      (format "        <tr><td><code>%s</code></td><td class=\"num\">%d</td><td><code>%s</code></td><td>%s</td></tr>"
              (esc rule)
              (count entries)
              (esc (str/join ", " (sort (distinct (map second entries)))))
              (esc (clip 220 (nth (first entries) 2)))))))

(defn- ledger-row [{:keys [t op subject disposition basis violations summary]}]
  (let [hold? (= :governor-hold t)]
    (format (str "        <tr><td>%s</td><td><code>%s</code></td><td><code>%s</code></td>"
                 "<td>%s</td><td>%s</td></tr>")
            (if hold?
              "<span class=\"critical\">governor-hold</span>"
              (str "<span class=\"ok\">" (esc (label t)) "</span>"))
            (esc op) (esc subject)
            (esc (label disposition))
            (esc (clip 200
                       (if hold?
                         (str (str/join ", " (map label basis)) " — "
                              (str/join " / " (map :detail violations)))
                         (str summary
                              (when (seq basis)
                                (str " [" (str/join "; " (map label basis)) "]")))))))))

(defn- jurisdiction-rows
  "Derived from `textiletrade.facts` for every jurisdiction the seeded
  orders actually use -- including the ones with NO spec-basis, which is
  exactly what produces the `:no-spec-basis` hold above."
  [orders]
  (for [j (sort (distinct (map :jurisdiction orders)))
        :let [sb (facts/spec-basis j)
              binding? (facts/forced-labor-import-ban-binding? j)]]
    (format "        <tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>"
            (esc j)
            (if sb (esc (:owner-authority sb))
                "<span class=\"critical\">no spec-basis — proposals HOLD</span>")
            (if sb (esc (clip 160 (:legal-basis sb))) "—")
            (if sb (esc (str/join ", " (facts/evidence-checklist j))) "—")
            (if binding?
              "<span class=\"warn\">binding forced-labor import ban</span>"
              "<span class=\"muted\">none binding</span>"))))

(defn- registry-rows [records kind-label]
  (for [r records]
    (format "        <tr><td><code>%s</code></td><td>%s</td><td><code>%s</code></td><td>%s</td><td>%s</td></tr>"
            (esc (get r "record_id")) (esc kind-label)
            (esc (get r "textile_order_id")) (esc (get r "jurisdiction"))
            (if (get r "immutable")
              "<span class=\"ok\">immutable draft</span>"
              "<span class=\"muted\">—</span>"))))

(defn- run-rows [runs]
  (for [r runs]
    (format "        <tr><td><code>%s</code></td><td><code>%s</code></td><td><code>%s</code></td><td class=\"num\">%s</td><td>%s</td></tr>"
            (esc (:thread-id r)) (esc (:op r)) (esc (:subject r))
            (esc (:confidence r))
            (route-badge r))))

